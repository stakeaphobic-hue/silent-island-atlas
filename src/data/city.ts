export function cityPlace(id: string) {
  return CITY_PLACES.find((p) => p.id === id);
}

export function searchCity(q: string) {
  const n = q.trim().toLowerCase();
  if (!n) return [];
  return CITY_PLACES.filter(
    (p) =>
      p.name.toLowerCase().includes(n) ||
      p.summary.toLowerCase().includes(n) ||
      p.tags.some((t) => t.toLowerCase().includes(n)) ||
      p.body.toLowerCase().includes(n),
  );
}
