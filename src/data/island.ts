export function placeById(id: string) {
  return PLACES.find((p) => p.id === id);
}

export function countyById(id: CountyId) {
  return COUNTIES.find((c) => c.id === id);
}

export function searchPlaces(q: string) {
  const n = q.trim().toLowerCase();
  if (!n) return PLACES;
  if (n === "bbc da" || n === "bbcda") {
    return PLACES.filter((p) => p.id === "bwc-da");
  }
  return PLACES.filter(
    (p) =>
      p.id.toLowerCase().includes(n) ||
      p.name.toLowerCase().includes(n) ||
      p.summary.toLowerCase().includes(n) ||
      p.tags?.some((t) => t.toLowerCase().includes(n)),
  );
}
