export function bayPlace(id: string) {
  return BAY_PLACES.find((p) => p.id === id);
}

export function searchBay(q: string) {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  return BAY_PLACES.filter(
    (p) =>
      p.name.toLowerCase().includes(s) ||
      p.shore.toLowerCase().includes(s) ||
      p.tags.some((t) => t.toLowerCase().includes(s)) ||
      p.summary.toLowerCase().includes(s),
  );
}
